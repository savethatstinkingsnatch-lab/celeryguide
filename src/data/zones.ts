export type ZoneGuide = (typeof zones)[number];
export type ZoneId = ZoneGuide["id"];

export function isZoneId(value: unknown): value is ZoneId {
  return zones.some((zone) => zone.id === value);
}

export function zoneById(id: ZoneId): ZoneGuide {
  const found = zones.find((zone) => zone.id === id);
  if (!found) throw new Error(`Unknown zone ${id}`);
  return found;
}

